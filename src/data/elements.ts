export type ElementCategory =
  | 'alkali-metal'
  | 'alkaline-earth'
  | 'transition-metal'
  | 'post-transition-metal'
  | 'metalloid'
  | 'reactive-nonmetal'
  | 'halogen'
  | 'noble-gas'
  | 'lanthanide'
  | 'actinide';

export interface ElementData {
  number: number;
  symbol: string;
  name: string;
  atomicMass: number;
  category: ElementCategory;
  group: number;
  period: number;
  block: 's' | 'p' | 'd' | 'f';
  electronConfiguration: string;
  shells: number[];
  oxidationStates: string;
  electronegativity: number | null;
  atomicRadius: number | null; // in picometers (pm)
  ionizationEnergy: number | null; // in kJ/mol
  meltingPoint: number | null; // in °C
  boilingPoint: number | null; // in °C
  density: number | null; // in g/cm³ or g/L for gases
  state: 'Solid' | 'Liquid' | 'Gas' | 'Synthetic';
  discoveryYear: number | string;
  summary: string;
  protons: number;
  neutrons: number;
  electrons: number;
}

