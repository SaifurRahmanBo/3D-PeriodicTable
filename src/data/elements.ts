// Helper lookups
export const ELEMENT_MAP = new Map<number, ElementData>(ELEMENTS.map((e) => [e.number, e]));
export const SYMBOL_MAP = new Map<string, ElementData>(ELEMENTS.map((e) => [e.symbol.toLowerCase(), e]));

export function getElement(numOrSymbol: number | string): ElementData | undefined {
  if (typeof numOrSymbol === 'number') {
    return ELEMENT_MAP.get(numOrSymbol);
  }
  return SYMBOL_MAP.get(numOrSymbol.toLowerCase());
}
